#!/usr/bin/env node
// Build-time public presentation catalogue; source mappings stay in PolicyService.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { PolicyService } from '../server/gcsp/policy/index.js';
import { SWATCH_HEX } from '../blocks/vehicle-matcher/modes/result-card.js';

export const SHADE_KEYS = ['stock.optionLabels.v1', 'stock.paintColourFamilies.v1', 'presentation.finishShades.v1'];
const normalise = (value) => value.normalize('NFKC').trim().replace(/\s+/gu, ' ').toLowerCase();
const target = new URL('../blocks/gcsp/kit/finish-shades-data.js', import.meta.url);

export async function projectFinishShades(policy, read) {
  const rows = await Promise.all(SHADE_KEYS.map((key) => policy.getAssumption(key, read)));
  for (const [index, row] of rows.entries()) {
    if (row.status !== 'ok' || row.value?.key !== SHADE_KEYS[index] || row.policyVersion !== read.policyVersion) {
      throw new Error(`Finish shades: unavailable or inconsistent ${SHADE_KEYS[index]}`);
    }
  }
  const [labels, families, choices] = rows.map((row) => row.value.value);
  if (families.schemaVersion !== 1 || choices.schemaVersion !== 1) throw new Error('Finish shades: unsupported mapping version');
  const paint = Object.create(null); const upholstery = Object.create(null);
  const add = (table, label, family) => {
    if (typeof label !== 'string' || !label.trim() || family !== null && !Object.hasOwn(SWATCH_HEX, family)) {
      throw new Error(`Finish shades: unsupported label/family ${label}`);
    }
    const key = normalise(label);
    if (Object.hasOwn(table, key) && table[key] !== family) throw new Error(`Finish shades: conflicting label ${label}`);
    table[key] = family;
  };
  for (const [code, label] of Object.entries(labels.paint)) {
    if (!Object.hasOwn(families.familyByCode, code)) throw new Error(`Finish shades: unmapped paint ${code}`);
    add(paint, label, families.familyByCode[code]);
  }
  for (const [label, code] of Object.entries(choices.paintAliases)) {
    if (!Object.hasOwn(families.familyByCode, code)) throw new Error(`Finish shades: unmapped paint alias ${code}`);
    add(paint, label, families.familyByCode[code]);
  }
  for (const label of choices.unknownPaintLabels) add(paint, label, null);
  for (const [code, family] of Object.entries(choices.upholsteryFamilyByCode)) {
    if (!Object.hasOwn(labels.upholstery, code)) throw new Error(`Finish shades: unlabelled upholstery ${code}`);
    add(upholstery, labels.upholstery[code], family);
  }
  for (const [label, family] of Object.entries(choices.upholsteryAliases)) add(upholstery, label, family);
  const ordered = (table) => Object.fromEntries(Object.entries(table).sort(([a], [b]) => a.localeCompare(b, 'en')));
  return { policyVersion: read.policyVersion, sourceKeys: SHADE_KEYS,
    sourceDigest: createHash('sha256').update(JSON.stringify(rows.map((row) => row.value))).digest('hex'),
    paint: ordered(paint), upholstery: ordered(upholstery) };
}

export function finishShadeModule(projection) {
  return '// Generated by scripts/project-finish-shades.mjs from PolicyService. Do not edit.\n'
    + `export const FINISH_SHADES = ${JSON.stringify(projection, null, 2)};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const policy = new PolicyService(); const read = { runId: 'finish-shades-build', asOf: new Date().toISOString() };
  const active = await policy.getActiveVersion(read);
  if (active.status !== 'ok') throw new Error('Finish shades: policy unavailable');
  const output = finishShadeModule(await projectFinishShades(policy, { ...read, policyVersion: active.policyVersion }));
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('Finish shade projection is stale; run node scripts/project-finish-shades.mjs');
    console.log('Finish shade projection matches shared policy.');
  } else {
    await writeFile(target, output);
    console.log('Wrote shared finish shade projection.');
  }
}
