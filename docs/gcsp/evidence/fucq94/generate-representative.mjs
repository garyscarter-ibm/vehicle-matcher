import { writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createMemoryRepository, createMemoryStore } from '../../../../server/gcsp/repository/index.js';
import { createPolicyService } from '../../../../server/gcsp/policy/index.js';
import { createDemoRuntime } from '../../../../server/gcsp/clock/index.js';
import { createBriefService } from '../../../../server/gcsp/brief/index.js';
import { createBriefEditorService } from '../../../../server/gcsp/brief/editor.js';
import { createManualContextService, createRepositoryManualPorts } from '../../../../server/gcsp/manual-context/index.js';
import { seedManualDemoContext } from '../../../../server/gcsp/manual-context/fixtures.js';
import { stock, providerValue, fact } from '../../../../server/test/helpers/employee-recommendation.js';
const digest = (v) => createHash('sha256').update(v).digest('hex');
const repository = createMemoryRepository({ store: createMemoryStore() });
await repository.open();
try {
  const policy = createPolicyService();
  const runtime = await createDemoRuntime({ repository, policy, environmentId: 'brief-representative', environmentKind: 'synthetic', policyAsOf: '2026-11-05T12:00:00.000Z', commandId: 'bootstrap', sessionNow: () => '2026-11-05T12:00:00.000Z' });
  if (runtime.status !== 'ok') throw Error(runtime.status);
  const { clock, identity } = runtime.value;
  const presenter = await identity.createPresenterSession('presenter');
  const acting = await identity.switchPrincipal(presenter.value.context, 'demo-paula', 'paula');
  const context = acting.value.context;
  const deps = { repository, policy, clock, identity, context };
  if ((await seedManualDemoContext(deps)).status !== 'ok') throw Error('seed');
  const first = structuredClone(stock(1, { equipment: fact({ towbar: true }) }));
  first.snapshot.display.name = 'BMW 320i M Sport Touring';
  first.snapshot.display.photo = '/assets/brand-hero/bmw.jpg';
  first.snapshot.display.images = [{ src: first.snapshot.display.photo, caption: 'BMW brand image, not this exact car' }];
  const second = structuredClone(stock(2, { fuel: fact('phev'), equipment: fact({ towbar: false }) }));
  second.snapshot.display.name = 'BMW 330e M Sport Pro Edition Touring with Technology Plus and Comfort Pack';
  const now = (await clock.now(context)).value.now;
  first.availability.availableFrom = now; second.availability.availableFrom = now;
  const source = { ...providerValue([first, second]), runId: context.runId, environmentId: context.environmentId, employeeId: context.employeeId };
  deps.provider = { resolve: async () => ({ status: 'ok', value: structuredClone(source) }) };
  deps.account = createManualContextService({ ...deps, ports: createRepositoryManualPorts(deps) });
  deps.brief = createBriefService(deps);
  const service = createBriefEditorService(deps);
  const editor = await service.readEditor(context);
  if (editor.status !== 'ok') throw Error(editor.status);
  const edited = structuredClone(editor);
  for (const p of Object.values(edited.value.initial.brief.preferences)) p.source = 'employee';
  Object.assign(edited.value.initial.brief.preferences.comfort, { value: 90, importance: 85 });
  Object.assign(edited.value.initial.brief.preferences.sportiness, { value: 90, importance: 75 });
  edited.value.initial.brief.preferences.economy.importance = 0;
  for (const key of ['seats', 'boot', 'equipment']) Object.assign(edited.value.initial.brief.essentials[key], { value: edited.value.context.practicalQuestions[key].no, state: 'draft', source: 'employee' });
  const preview = await service.previewDraft(context, { kind: 'unsaved-draft', baseBriefVersion: 0, draftVersion: 0, brief: edited.value.initial.brief });
  if (preview.status !== 'ok' || preview.value.eligibleCount !== 1 || !preview.value.decisions.some((d) => d.gateStatus === 'needs-confirmation')) throw Error('Representative gates missing: ' + JSON.stringify({ status: preview.status, decisions: preview.value?.decisions.map((d) => ({ gate: d.gateStatus, blockers: d.blockers, unknowns: d.unknowns })) }));
  const payload = JSON.stringify({ synthetic: true, generatedAt: '2026-11-05T12:00:00.000Z', editor, edited, preview }, null, 2) + '\n';
  const paths = ['server/gcsp/brief/editor.js', 'server/gcsp/brief/index.js', 'server/gcsp/recommendation/index.js', 'server/test/helpers/employee-recommendation.js', 'docs/gcsp/evidence/fucq94/generate-representative.mjs'];
  const sources = Object.fromEntries(await Promise.all(paths.map(async (p) => [p, digest(await readFile(new URL('../../../../' + p, import.meta.url)))])));
  await writeFile(new URL('representative-snapshot.json', import.meta.url), payload);
  await writeFile(new URL('representative-identity.json', import.meta.url), JSON.stringify({ snapshotSha256: digest(payload), sources, scope: 'Synthetic generated layout evidence, not a live runtime connection.' }, null, 2) + '\n');
  console.log(JSON.stringify({ eligible: preview.value.eligibleCount, unknown: preview.value.decisions.filter((d) => d.gateStatus === 'needs-confirmation').length, snapshotSha256: digest(payload) }));
} finally { await repository.close(); }
